import {
  isCollectionsSchema,
  normalizeFieldConfig,
  normalizeSchema,
} from '../generator.js';

/**
 * @param {string} key
 */
function safePropName(key) {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

/**
 * @param {string} name
 */
function toPascalInterface(name) {
  const cleaned = String(name).replace(/[^a-zA-Z0-9]+/g, ' ');
  const parts = cleaned.split(/\s+/).filter(Boolean);
  const pascal = parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1).toLowerCase()).join('');
  return pascal || 'Collection';
}

/**
 * @typedef {{ cols?: Record<string, Record<string, unknown>> }} TsEnv
 */

/**
 * @param {unknown} cfgRaw
 * @param {TsEnv} env
 */
function tsType(cfgRaw, env) {
  const cfg = normalizeFieldConfig(cfgRaw);

  /** @type {string} */
  let core;

  switch (cfg.type) {
    case 'uuid':
    case 'name':
    case 'email':
    case 'phone':
    case 'text':
    case 'template':
    case 'date':
    case 'address':
      core = 'string';
      break;
    case 'number':
    case 'float':
      core = 'number';
      break;
    case 'boolean':
      core = 'boolean';
      break;
    case 'enum': {
      const values = cfg.values;
      if (!Array.isArray(values)) {
        core = 'unknown';
        break;
      }
      core = values.map((v) => JSON.stringify(v)).join(' | ');
      break;
    }
    case 'object': {
      const props = cfg.properties;
      if (props === null || typeof props !== 'object' || Array.isArray(props)) {
        core = 'Record<string, unknown>';
        break;
      }
      const entries = Object.entries(/** @type {Record<string, unknown>} */ (props)).map(
        ([k, v]) => `${safePropName(k)}: ${tsType(v, env)}`
      );
      core = `{ ${entries.join('; ')} }`;
      break;
    }
    case 'array':
      core = `${tsType(cfg.items, env)}[]`;
      break;
    case 'ref': {
      const col = /** @type {string} */ (cfg.collection);
      const fld = /** @type {string} */ (cfg.field);
      const cols = env.cols;
      if (!cols || !cols[col] || !(fld in cols[col])) {
        core = 'unknown';
        break;
      }
      core = tsType(cols[col][fld], env);
      break;
    }
    default:
      core = 'unknown';
  }

  if (typeof cfg.nullChance === 'number' && cfg.nullChance > 0) {
    const needsWrap = /\|/.test(core);
    const base = needsWrap ? `(${core})` : core;
    return `${base} | null`;
  }
  return core;
}

/**
 * @param {Record<string, unknown>} schemaRoot
 */
function emitFlat(schemaRoot) {
  const norm = normalizeSchema(schemaRoot);
  const env = /** @type {TsEnv} */ ({});
  const lines = ['/** Generated by mock-craft (mcraft --types) */', '', 'export interface MockRow {'];

  for (const [k, raw] of Object.entries(norm)) {
    lines.push(`  ${safePropName(k)}: ${tsType(raw, env)};`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

/**
 * @param {Record<string, Record<string, unknown>>} collections
 */
function emitCollections(collections) {
  const env = /** @type {TsEnv} */ ({ cols: collections });
  const lines = ['/** Generated by mock-craft (mcraft --types) */', ''];

  for (const colName of Object.keys(collections)) {
    const iface = `${toPascalInterface(colName)}Row`;
    lines.push(`export interface ${iface} {`);
    const norm = normalizeSchema(collections[colName]);
    for (const [k, raw] of Object.entries(norm)) {
      lines.push(`  ${safePropName(k)}: ${tsType(raw, env)};`);
    }
    lines.push('}', '');
  }

  return lines.join('\n');
}

/**
 * @param {unknown} schema parsed JSON schema (flat or _collections)
 * @returns {string} TypeScript source
 */
export function emitTypeScriptFromSchema(schema) {
  if (schema === null || typeof schema !== 'object') {
    throw new Error('Schema must be an object.');
  }
  if (isCollectionsSchema(schema)) {
    return emitCollections(
      /** @type {{ _collections: Record<string, Record<string, unknown>> }} */ (schema)._collections
    );
  }
  return emitFlat(/** @type {Record<string, unknown>} */ (schema));
}
